#!/usr/bin/env node
/**
 * Bundle the LifePM browser plugin into the DSH client-module format.
 *
 * The web shell loads a plugin's `./client` export as a classic script that
 * registers one lazy-CJS factory:
 *
 *   window.__ModuleLoader__.load({ id: "<package>", factory: (require) => {...} })
 *
 * The factory body is esbuild's CommonJS output with `react` left external, so
 * module-level side effects (the stylesheet injection) only run when the shell
 * materializes the plugin.
 */

import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const packageJson = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const outfile = path.join(root, 'lib', 'client.js')

const result = await build({
  entryPoints: [path.join(root, 'src', 'client', 'index.jsx')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  external: ['react'],
  loader: { '.css': 'text' },
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  legalComments: 'none',
  charset: 'utf8',
  write: false,
  logLevel: 'warning',
})

const code = result.outputFiles[0].text
const banner = `/* LifePM ${packageJson.version} — generated by plugin/scripts/build.mjs; edit src/client instead. */\n`
const wrapped = `${banner}window.__ModuleLoader__.load({
	id: ${JSON.stringify(packageJson.name)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${indent(code, 2)}
		if (exports.default !== undefined && exports.apply === undefined) {
			exports.apply = exports.default.apply;
			exports.inject = exports.default.inject;
		}
		return module.exports;
	}
});
`

await mkdir(path.dirname(outfile), { recursive: true })
await writeFile(outfile, wrapped, 'utf8')
console.log(`built ${path.relative(process.cwd(), outfile)} (${(wrapped.length / 1024).toFixed(1)} kB)`)

/** @param {string} text @param {number} spaces */
function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text.split('\n').map((line) => (line === '' ? line : pad + line)).join('\n')
}
